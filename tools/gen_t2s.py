"""Generate tools/t2s_map.py (Traditional -> Simplified characters used in the site) with OpenCC.
Run with a Python that has `opencc` installed:  python tools/gen_t2s.py"""
import os
import opencc

HERE = os.path.dirname(os.path.abspath(__file__))
cc = opencc.OpenCC("t2s")
chars = set()
for name in ("data.py", "app_strings.py", "kiosk_strings.py", "build.py"):
    with open(os.path.join(HERE, name), encoding="utf-8") as f:
        chars |= {c for c in f.read() if "一" <= c <= "鿿"}
m = {c: cc.convert(c) for c in sorted(chars) if cc.convert(c) != c}
lines = ["# -*- coding: utf-8 -*-", "# Generated by tools/gen_t2s.py - do not edit by hand.", "T2S = {"]
row = []
for k, v in m.items():
    row.append('"%s": "%s",' % (k, v))
    if len(row) == 8:
        lines.append("    " + " ".join(row)); row = []
if row:
    lines.append("    " + " ".join(row))
lines += ["}", "PHRASES = []", ""]
with open(os.path.join(HERE, "t2s_map.py"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print(len(m), "chars mapped")
